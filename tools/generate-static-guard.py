"""Turns the pack analyzer's guard lists into MultiCore's static guard.

    gradlew analyzePack -Pmods=<mods folder> -Pout=build/pack-report-guard
    python tools/generate-static-guard.py build/pack-report-guard

Writes src/main/java/com/multicore/mixin/guard/StaticGuardCarrier.java (the classes to patch) and
src/main/resources/multicore-guard.txt (which fields, which classes lock everything). Run it again after adding mods.
"""
import os
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "build/pack-report-guard"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def lines(name):
    with open(os.path.join(src, name), encoding="utf-8") as f:
        return [l.strip() for l in f if l.strip()]

# Already made safe another way (per-thread, concurrent, or whole-class locks of their own carriers).
HANDLED_FIELDS = {
    "com/simibubi/create/content/kinetics/belt/BeltHelper.uprightCache",
    "com/simibubi/create/content/kinetics/belt/BeltShapes.cache",
    "com/simibubi/create/content/kinetics/belt/BeltShapes.collisionCache",
    "com/simibubi/create/content/logistics/chute/ChuteShapes.cache",
    "com/simibubi/create/content/logistics/chute/ChuteShapes.collisionCache",
    "com/simibubi/create/content/logistics/tunnel/BrassTunnelBlockEntity.distributed",
    "com/simibubi/create/content/logistics/tunnel/BrassTunnelBlockEntity.full",
    "com/simibubi/create/content/kinetics/deployer/DeployerHandler.CAPTURED_BLOCK_DROPS",
}
OWN_CARRIERS = {
    "com/simibubi/create/content/kinetics/TorquePropagator",
    "com/simibubi/create/content/kinetics/KineticNetwork",
    "com/simibubi/create/content/redstone/link/RedstoneLinkNetworkHandler",
    "com/simibubi/create/content/trains/track/TrackPropagator",
    "com/simibubi/create/content/trains/graph/TrackGraph",
    "com/simibubi/create/content/trains/GlobalRailwayManager",
    "com/simibubi/create/content/logistics/packagerLink/LogisticsManager",
    "com/simibubi/create/content/logistics/packagerLink/GlobalLogisticsManager",
    "net/mehvahdjukaar/supplementaries/common/block/hourglass/HourglassTimesManager",
    "fr/rakambda/fallingtree/neoforge/common/FallingTreeCommonsImpl",
    "com/railwayteam/railways/util/MixinVariables",
    "xaero/pac/common/server/core/ServerCore",
}

fields = [f for f in lines("guard-fields.txt") if f not in HANDLED_FIELDS]
field_set = set(fields)
saved = [c for c in lines("guard-saveddata.txt") if c not in OWN_CARRIERS]
classes = set(saved)
for c in lines("guard-classes.txt"):
    if c not in OWN_CARRIERS:
        classes.add(c)
classes = sorted(classes)

with open(os.path.join(root, "src/main/resources/multicore-guard.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# Generated by tools/generate-static-guard.py from the pack analyzer. F = shared static field, S = per-world state class.\n")
    for x in fields:
        f.write("F " + x + "\n")
    for x in saved:
        f.write("S " + x + "\n")


# Several small carriers: a class that loads before mixins apply only costs its own carrier, not the whole guard.
CHUNK = 40
out_dir = os.path.join(root, "src/main/java/com/multicore/mixin/guard")
for old in os.listdir(out_dir):
    if old.startswith("StaticGuardCarrier"):
        os.remove(os.path.join(out_dir, old))
TEMPLATE = '''package com.multicore.mixin.guard;

import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Pseudo;

/**
 * GENERATED by tools/generate-static-guard.py from the pack analyzer (do not edit by hand; run it again after adding
 * mods). Empty on purpose: {@code MultiCoreMixinPlugin.postApply} makes the methods of these mod classes that use a
 * shared static collection changed while the game runs (multicore-guard.txt, "F") take the mod lock on tick threads,
 * and every method of the mods' per-world state classes ("S": SavedData and maps keyed by world, shared by every
 * region thread of a world). Everything else of every mod runs without the lock.
 */
@Pseudo
@Mixin(targets = {
%s
}, remap = false)
public abstract class %s {
}
'''
names = []
for n in range(0, len(classes), CHUNK):
    name = "StaticGuardCarrier%02d" % (n // CHUNK)
    names.append(name)
    targets = ",\n".join('        "' + c.replace("/", ".") + '"' for c in classes[n:n + CHUNK])
    with open(os.path.join(out_dir, name + ".java"), "w", encoding="utf-8", newline="\n") as f:
        f.write(TEMPLATE % (targets, name))
config = {
    "required": False, "minVersion": "0.8", "package": "com.multicore.mixin",
    "plugin": "com.multicore.compat.MultiCoreMixinPlugin", "compatibilityLevel": "JAVA_21",
    "mixins": ["guard." + n for n in names], "injectors": {"defaultRequire": 0},
}
import json
with open(os.path.join(root, "src/main/resources/multicore-guard.mixins.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(config, f, indent=2)
    f.write("\n")
print("static guard: %d fields, %d per-world classes, %d classes patched in %d carriers" % (len(fields), len(saved), len(classes), len(names)))
